// Turns a transcript into a Markdown summary with timestamped highlights.
// The model call is injected as `complete`, so it works with the OpenAI API
// and with the ChatGPT web app alike.

// Transcripts within singlePassTokens go to the model in one request. Longer
// ones are condensed into notes chunk by chunk first. ChatGPT's web app takes
// much shorter messages than the API, and handles one at a time per tab.
export const API_LIMITS = { singlePassTokens: 60_000, chunkTokens: 30_000, parallel: true };
export const CHATGPT_LIMITS = { singlePassTokens: 12_000, chunkTokens: 9_000, parallel: false };

const LINE_WINDOW_SECONDS = 20;

// Rough count: ~4 characters per token for Latin text; other scripts spend
// far more tokens per character, so they are counted conservatively.
export function estimateTokens(text) {
  const nonAscii = text.replace(/[\x00-\x7f]/g, '').length;
  return Math.ceil((text.length - nonAscii) / 4 + nonAscii * 0.8);
}

export function formatTimestamp(totalSeconds) {
  const s = Math.max(0, Math.floor(totalSeconds));
  const hours = Math.floor(s / 3600);
  const minutes = Math.floor((s % 3600) / 60);
  const seconds = String(s % 60).padStart(2, '0');
  return hours ? `${hours}:${String(minutes).padStart(2, '0')}:${seconds}` : `${minutes}:${seconds}`;
}

// Merges caption segments into "[m:ss] text" lines about 20 seconds long, which
// keeps timestamps precise enough while spending far fewer tokens on them.
export function formatTranscript(segments) {
  const lines = [];
  let start = null;
  let parts = [];
  for (const segment of segments) {
    if (start === null) start = segment.start;
    else if (segment.start - start >= LINE_WINDOW_SECONDS) {
      lines.push(`[${formatTimestamp(start)}] ${parts.join(' ')}`);
      start = segment.start;
      parts = [];
    }
    parts.push(segment.text);
  }
  if (parts.length) lines.push(`[${formatTimestamp(start)}] ${parts.join(' ')}`);
  return lines;
}

function chunkLines(lines, maxTokens) {
  const chunks = [];
  let current = [];
  let size = 0;
  for (const line of lines) {
    const tokens = estimateTokens(line);
    if (size + tokens > maxTokens && current.length) {
      chunks.push(current.join('\n'));
      current = [];
      size = 0;
    }
    current.push(line);
    size += tokens;
  }
  if (current.length) chunks.push(current.join('\n'));
  return chunks;
}

// YouTube's own names for auto-generated tracks usually say so already.
export function describeTranscriptLanguage({ languageName, autoGenerated }) {
  if (!languageName) return '';
  return autoGenerated && !/auto/i.test(languageName) ? `${languageName} (auto-generated)` : languageName;
}

const LIST_ITEM = /^\s*(?:[-*•]|\d+[.)])\s/;

// Keeps only the requested sections: drops what a model or chat UI puts before
// the first heading, and chat-style offers after the last highlight
// ("Want me to …?").
function tidy(markdown) {
  const start = markdown.search(/^#{1,3}\s/m);
  const lines = (start > 0 ? markdown.slice(start) : markdown).split('\n');
  const lastItem = lines.findLastIndex((line) => LIST_ITEM.test(line));
  if (lastItem > lines.findLastIndex((line) => /^#{1,6}\s/.test(line))) {
    let end = lastItem + 1;
    while (end < lines.length && /^\s+\S/.test(lines[end])) end++; // continuation lines
    lines.length = end;
  }
  return lines.join('\n').trim();
}

const languageInstruction = (language) =>
  language && language !== 'auto' ? language : 'the same language as the transcript';

function summaryInstructions(language) {
  return `You summarize YouTube videos from their transcripts. Keep it short: the reader should get the gist in under a minute.

Write in ${languageInstruction(language)}. Respond in Markdown with exactly these two sections and nothing else:

## Summary
2 or 3 sentences, at most 60 words: what the video is about and its main takeaway.

## Key Highlights
At most 8 bullets in chronological order (3 to 5 for videos under 10 minutes), each in this exact form:
- [m:ss] **Short headline** — one short sentence.
Each bullet is under 20 words and starts with the timestamp of the transcript line where the point begins, in square brackets, exactly as in the transcript (for example [4:05] or [1:02:30]).

Rules:
- Use only what the video says. The title and description are context; do not invent details.
- Transcripts are often auto-generated; silently fix obvious recognition errors.
- Skip sponsor reads, intros, outros, and requests to like or subscribe unless they are the topic.
- Keep the whole answer under 200 words. No preamble, closing remarks, or follow-up offers.`;
}

function notesInstructions(language) {
  return `You are reading one part of a long YouTube video transcript. Write brief notes in ${languageInstruction(language)} on the main points of this part, in order: at most 12 bullets, each under 25 words. Each note starts with the timestamp where the point begins, copied from the transcript, e.g. "- [12:05] ...". Keep key names and numbers. Output only the bullets.`;
}

function videoContext(transcript) {
  const duration = transcript.lengthSeconds || transcript.segments.at(-1)?.start || 0;
  const lines = [
    `Title: ${transcript.title || 'unknown'}`,
    `Channel: ${transcript.author || 'unknown'}`,
    `Duration: ${formatTimestamp(duration)}`,
    `Transcript language: ${describeTranscriptLanguage(transcript) || 'unknown'}`,
  ];
  const description = transcript.description.trim().slice(0, 1500);
  if (description) lines.push('', 'Description:', '"""', description, '"""');
  return lines.join('\n');
}

/**
 * @param complete({ instructions, input, onText }) => Promise<string> the model call
 * @param limits   API_LIMITS or CHATGPT_LIMITS
 * @param label    model name for status messages
 * @param onStatus(text) progress messages for the UI
 * @param onText(markdown) the summary so far, while it streams
 */
export async function summarize({ transcript, language, complete, limits, label, onStatus, onText }) {
  const lines = formatTranscript(transcript.segments);
  const fullText = lines.join('\n');
  const context = videoContext(transcript);

  let body;
  if (estimateTokens(fullText) <= limits.singlePassTokens) {
    body = `Transcript (each line starts with its [timestamp]):\n"""\n${fullText}\n"""`;
  } else {
    const chunks = chunkLines(lines, limits.chunkTokens);
    const readPart = (chunk, i) =>
      complete({
        instructions: notesInstructions(language),
        input: `${context}\n\nTranscript part ${i + 1} of ${chunks.length}:\n"""\n${chunk}\n"""`,
      });
    let notes;
    if (limits.parallel) {
      onStatus?.(`Long video: reading the transcript in ${chunks.length} parts…`);
      notes = await Promise.all(chunks.map(readPart));
    } else {
      notes = [];
      for (const [i, chunk] of chunks.entries()) {
        onStatus?.(`Long video: reading part ${i + 1} of ${chunks.length}…`);
        notes.push(await readPart(chunk, i));
      }
    }
    body = `Notes taken from the full transcript, in order (timestamps preserved):\n"""\n${notes.join('\n')}\n"""`;
  }

  onStatus?.(`Summarizing with ${label}…`);
  const markdown = await complete({
    instructions: summaryInstructions(language),
    input: `${context}\n\n${body}`,
    onText: (text) => onText?.(tidy(text)),
  });
  return tidy(markdown);
}
